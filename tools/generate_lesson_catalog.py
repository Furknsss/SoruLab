#!/usr/bin/env python3
"""Validate reviewed lesson metadata and deterministically generate Kotlin. No scraping."""
import argparse
import datetime
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT / "app/src/main/java/com/example/ui/screens/GeneratedLessonContent.kt"

def render(data):
    if data["schemaVersion"] != 1:
        raise ValueError("Unsupported schema")
    models = (ROOT / "app/src/main/java/com/example/data/SoruLabModels.kt").read_text(encoding="utf-8")
    scope = set(re.findall(r'topicEntry\("([^"]+)", "([^"]+)"', models))
    rows, seen = [], set()
    quote = lambda s: json.dumps(s, ensure_ascii=False).replace("$", "\\$")
    for e in data["entries"]:
        v = e["video"]
        if (e["topicId"], e["subjectId"]) not in scope:
            raise ValueError("Unknown curriculum scope")
        if not re.fullmatch(r"[A-Za-z0-9_-]{11}", v["videoId"]):
            raise ValueError("Invalid video ID")
        if v["sourceUrl"] != "https://www.youtube.com/watch?v=" + v["videoId"]:
            raise ValueError("Missing canonical publisher source")
        datetime.date.fromisoformat(v["reviewedOn"])
        if datetime.date.fromisoformat(v["reviewedOn"]) > datetime.date.today():
            raise ValueError("Future review")
        start, end = v["startSeconds"], v["endSeconds"]
        if type(start) is not int or start < 0 or (end is not None and (type(end) is not int or end <= start)):
            raise ValueError("Invalid chapter range")
        if any(not v[k].strip() for k in ("teacher", "title", "sourceOfTimestamp", "detail")):
            raise ValueError("Missing evidence")
        if e["phrases"] and not v["outcomeId"]:
            raise ValueError("Skill phrases need outcome ID")
        identity = (e["subjectId"], e["topicId"], v["videoId"], start)
        if identity in seen:
            raise ValueError("Duplicate lesson")
        seen.add(identity)
        args = [quote(v[k]) for k in ("teacher", "title", "videoId")]
        args += [str(start)]
        args += [quote(v[k]) for k in ("detail", "sourceOfTimestamp", "sourceUrl", "reviewedOn", "outcomeId")]
        args += [str(end) if end is not None else "null"]
        rows.append("        LessonEntry(" + quote(e["subjectId"]) + ", " + quote(e["topicId"]) +
                    ", LessonVideo(" + ", ".join(args) + "), listOf(" +
                    ", ".join(map(quote, e["phrases"])) + "))")
    return ("package com.example.ui.screens\n\n"
            "// Generated by tools/generate_lesson_catalog.py; edit content/lessons.json.\n"
            "internal object GeneratedLessonContent {\n    val entries = listOf(\n" +
            ",\n".join(rows) + "\n    )\n}\n")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = render(json.loads((ROOT / "content/lessons.json").read_text(encoding="utf-8")))
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != result:
            sys.exit("Generated catalog is stale. Run python3 tools/generate_lesson_catalog.py")
        print("Lesson metadata and generated Kotlin are consistent.")
    else:
        TARGET.write_text(result, encoding="utf-8")
